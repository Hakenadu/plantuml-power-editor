import { GlobalStyle, StyleProps, globalStyleKey } from './plantuml-styles';

/**
 * Themes shipped with the editor. They are plain `<style>` rules (no `!theme`), so a themed
 * diagram renders the same everywhere and every value stays editable in the style panel.
 *
 * Constraints of the browser engine that shape these themes: gradients and shadows are not
 * rendered, so the looks are built from colors, corner radius, line thickness, line style and
 * fonts. `title` only sets FontColor and FontSize, and `element` always sets both as well,
 * because title rules leak onto all elements of component and use case diagrams otherwise.
 */
export interface BuiltinTheme extends GlobalStyle {
  id: string;
  name: string;
  /** Preview colors: background, two fills, accent. */
  swatch: [string, string, string, string];
}

const box = (
  BackGroundColor: string,
  LineColor: string,
  FontColor?: string,
  extra: StyleProps = {},
): StyleProps => ({ BackGroundColor, LineColor, ...(FontColor ? { FontColor } : {}), ...extra });

