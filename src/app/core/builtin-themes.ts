const KEYS = new Map(BUILTIN_THEMES.map((t) => [globalStyleKey(t), t.id]));

/** Id of the built-in theme whose styles match exactly, if any. */
export function matchBuiltinTheme(style: GlobalStyle): string | null {
  return KEYS.get(globalStyleKey(style)) ?? null;
}
